//! Generated bindings for Plasma's output protocols.
//!
//! The XML is vendored from `KDE/plasma-wayland-protocols` (MIT-CMU; see
//! `protocols/`) instead of taken from the `wayland-protocols-plasma`
//! crate, whose copy stops at `kde_output_device_v2` version 11. Current
//! `KWin` sends mode events from later versions (`flags`, `cvt`), and an
//! event the bindings do not know aborts the whole connection, so the
//! bindings must be at least as new as the compositor's protocol.

#![allow(
    dead_code,
    non_camel_case_types,
    non_upper_case_globals,
    non_snake_case,
    unused_imports,
    unused_qualifications,
    missing_docs,
    missing_debug_implementations,
    clippy::all,
    clippy::pedantic,
    clippy::cargo,
    clippy::allow_attributes_without_reason,
    clippy::empty_structs_with_brackets,
    clippy::semicolon_outside_block,
    reason = "generated by wayland-scanner"
)]

pub mod output_device {
    //! Client side of `kde_output_device_v2`.
    use wayland_client;
    use wayland_client::protocol::*;

    pub mod __interfaces {
        //! Interface descriptors.
        use wayland_client::backend as wayland_backend;
        use wayland_client::protocol::__interfaces::*;
        wayland_scanner::generate_interfaces!("protocols/kde-output-device-v2.xml");
    }
    use self::__interfaces::*;

    wayland_scanner::generate_client_code!("protocols/kde-output-device-v2.xml");
}

pub mod output_management {
    //! Client side of `kde_output_management_v2`.
    use wayland_client;
    use wayland_client::protocol::*;

    use super::output_device::*;

    pub mod __interfaces {
        //! Interface descriptors.
        use wayland_client::backend as wayland_backend;
        use wayland_client::protocol::__interfaces::*;

        use super::super::output_device::__interfaces::*;
        wayland_scanner::generate_interfaces!("protocols/kde-output-management-v2.xml");
    }
    use self::__interfaces::*;

    wayland_scanner::generate_client_code!("protocols/kde-output-management-v2.xml");
}

