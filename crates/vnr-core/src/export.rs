//! Exports a layout as compositor configuration.
//!
//! Configuration applied through wlr-output-management is transient on
//! niri and sway: it is lost when the compositor restarts. These exporters
//! produce the snippet that makes it permanent.

use std::fmt::{self, Write as _};
use std::str::FromStr;

use crate::error::ParseError;
use crate::model::{AdaptiveSync, Layout, Output};

/// A configuration format Vernier can export to.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Format {
    /// niri's KDL `output` blocks.
    Niri,
    /// sway's `output` commands.
    Sway,
}

impl Format {
    /// Every format.
    pub const ALL: [Self; 2] = [Self::Niri, Self::Sway];

    /// The format's identifier on the command line.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Niri => "niri",
            Self::Sway => "sway",
        }
    }
}

impl fmt::Display for Format {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

impl FromStr for Format {
    type Err = ParseError;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        Self::ALL
            .into_iter()
            .find(|f| f.as_str().eq_ignore_ascii_case(s.trim()))
            .ok_or_else(|| ParseError::new("export format", s))
    }
}

/// Renders `layout` in `format`.
#[must_use]
pub fn render(layout: &Layout, format: Format) -> String {
    match format {
        Format::Niri => niri(layout),
        Format::Sway => sway(layout),
    }
}

/// Quotes a string as a KDL (v1 and v2 compatible) string literal.
fn kdl_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// niri `output` blocks, one per output.
///
/// niri has no mirroring; a mirrored output is written as a comment so the
/// intent is visible when the snippet is pasted.
#[must_use]
pub fn niri(layout: &Layout) -> String {
    let mut out = String::from("// Generated by Vernier (vnr export --format niri)\n");
    for output in &layout.outputs {
        // `writeln!` into a `String` cannot fail.
        let _ = writeln!(out, "\noutput {} {{", kdl_string(&output.name));
        write_niri_body(&mut out, output);
        out.push_str("}\n");
    }
    out
}

fn write_niri_body(out: &mut String, output: &Output) {
    if !output.enabled {
        out.push_str("    off\n");
        return;
    }
    if let Some(source) = &output.mirror_of {
        let _ = writeln!(out, "    // mirrors {source}: niri cannot mirror outputs");
    }
    if let Some(mode) = output.mode {
        let text = if mode.refresh_mhz == 0 {
            format!("{}x{}", mode.width, mode.height)
        } else {
            format!("{}x{}@{}", mode.width, mode.height, mode.refresh_hz())
        };
        let _ = writeln!(out, "    mode {}", kdl_string(&text));
    }
    let _ = writeln!(out, "    scale {}", output.scale);
    let _ = writeln!(
        out,
        "    transform {}",
        kdl_string(output.transform.as_str())
    );
    let _ = writeln!(
        out,
        "    position x={} y={}",
        output.position.x, output.position.y
    );
    match output.adaptive_sync {
        Some(AdaptiveSync::Always) => out.push_str("    variable-refresh-rate\n"),
        Some(AdaptiveSync::Automatic) => {
            out.push_str("    variable-refresh-rate on-demand=true\n");
        }
        Some(AdaptiveSync::Disabled) | None => {}
    }
    if output.primary {
        out.push_str("    focus-at-startup\n");
    }
}

/// sway `output` commands, one line per output.
///
/// sway mirrors nothing natively either; mirrored outputs become comments.
#[must_use]
pub fn sway(layout: &Layout) -> String {
    let mut out = String::from("# Generated by Vernier (vnr export --format sway)\n");
    for output in &layout.outputs {
        let name = kdl_string(&output.name);
        if !output.enabled {
            let _ = writeln!(out, "output {name} disable");
            continue;
        }
        if let Some(source) = &output.mirror_of {
            let _ = writeln!(out, "# {name} mirrors {source}: sway cannot mirror outputs");
        }
        let _ = write!(out, "output {name} enable");
        if let Some(mode) = output.mode {
            let _ = write!(out, " mode {mode}");
        }
        let _ = write!(
            out,
            " position {} {} scale {} transform {}",
            output.position.x, output.position.y, output.scale, output.transform
        );
        match output.adaptive_sync {
            Some(AdaptiveSync::Always | AdaptiveSync::Automatic) => {
                out.push_str(" adaptive_sync on");
            }
            Some(AdaptiveSync::Disabled) => out.push_str(" adaptive_sync off"),
            None => {}
        }
        out.push('\n');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{Mode, Position, Scale, Transform};

    fn layout() -> Layout {
        let mut a = Output::new("eDP-1");
        a.mode = Some(Mode::new(2880, 1800, 120_000));
        a.scale = Scale::from_millis(1750).unwrap();
        a.adaptive_sync = Some(AdaptiveSync::Automatic);
        let mut b = Output::new("DP-1");
        b.mode = Some(Mode::new(2560, 1440, 59_951));
        b.position = Position::new(1646, 0);
        b.transform = Transform::Rotate90;
        let mut c = Output::new("HDMI-A-1");
        c.enabled = false;
        Layout::new(vec![a, b, c])
    }

    #[test]
    fn niri_snippet() {
        let text = niri(&layout());
        assert!(
            text.contains("output \"eDP-1\" {\n    mode \"2880x1800@120.000\"\n    scale 1.75\n")
        );
        assert!(text.contains("    variable-refresh-rate on-demand=true\n"));
        assert!(text.contains("    transform \"90\"\n    position x=1646 y=0\n"));
        assert!(text.contains("output \"HDMI-A-1\" {\n    off\n}"));
    }

    #[test]
    fn sway_snippet() {
        let text = sway(&layout());
        assert!(text.contains(
            "output \"DP-1\" enable mode 2560x1440@59.951Hz position 1646 0 scale 1 transform 90\n"
        ));
        assert!(text.contains("output \"HDMI-A-1\" disable\n"));
    }

    #[test]
    fn kdl_strings_are_escaped() {
        assert_eq!(kdl_string(r#"a"b\c"#), r#""a\"b\\c""#);
    }
}
