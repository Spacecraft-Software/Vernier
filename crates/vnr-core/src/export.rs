//! Exports a layout as compositor configuration.
//!
//! Configuration applied through wlr-output-management is transient on
//! niri and sway: it is lost when the compositor restarts. These exporters
//! produce the snippet that makes it permanent, either in the compositor's
//! own configuration or as a profile for kanshi or shikane, which reapply a
//! layout whenever the matching outputs are connected.

use std::fmt::{self, Write as _};
use std::str::FromStr;

use crate::error::ParseError;
use crate::model::{AdaptiveSync, Layout, Output, Scale};

/// A configuration format Vernier can export to.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Format {
    /// niri's KDL `output` blocks.
    Niri,
    /// sway's `output` commands.
    Sway,
    /// A kanshi `profile` block.
    Kanshi,
    /// A shikane TOML `[[profile]]`.
    Shikane,
    /// home-manager's `services.kanshi` module, as a Nix attribute set.
    HomeManager,
}

impl Format {
    /// Every format.
    pub const ALL: [Self; 5] = [
        Self::Niri,
        Self::Sway,
        Self::Kanshi,
        Self::Shikane,
        Self::HomeManager,
    ];

    /// The format's identifier on the command line.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Niri => "niri",
            Self::Sway => "sway",
            Self::Kanshi => "kanshi",
            Self::Shikane => "shikane",
            Self::HomeManager => "home-manager",
        }
    }
}

impl fmt::Display for Format {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

impl FromStr for Format {
    type Err = ParseError;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        Self::ALL
            .into_iter()
            .find(|f| f.as_str().eq_ignore_ascii_case(s.trim()))
            .ok_or_else(|| ParseError::new("export format", s))
    }
}

/// Renders `layout` in `format`.
#[must_use]
pub fn render(layout: &Layout, format: Format) -> String {
    match format {
        Format::Niri => niri(layout),
        Format::Sway => sway(layout),
        Format::Kanshi => kanshi(layout),
        Format::Shikane => shikane(layout),
        Format::HomeManager => home_manager(layout),
    }
}

/// The file, next to niri's `config.kdl`, that Vernier persists a layout
/// to; the main config pulls it in with `include "vernier.kdl"`.
pub const NIRI_INCLUDE_FILE: &str = "vernier.kdl";

/// The first line of every exported snippet starts with this, after the
/// format's comment marker.
const GENERATED: &str = "Generated by Vernier";

/// Whether `existing` was written by one of these exporters, so replacing
/// it loses nothing a person wrote.
#[must_use]
pub fn is_generated(existing: &str) -> bool {
    ["// ", "# "].iter().any(|marker| {
        existing
            .strip_prefix(marker)
            .is_some_and(|rest| rest.starts_with(GENERATED))
    })
}

/// The profile name kanshi, shikane and home-manager snippets use.
pub const PROFILE_NAME: &str = "vernier";

/// Quotes a string as a KDL (v1 and v2 compatible) string literal.
fn kdl_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// niri `output` blocks, one per output.
///
/// niri has no mirroring; a mirrored output is written as a comment so the
/// intent is visible when the snippet is pasted.
#[must_use]
pub fn niri(layout: &Layout) -> String {
    let mut out = String::from("// Generated by Vernier (vnr layout export --to niri)\n");
    for output in &layout.outputs {
        // `writeln!` into a `String` cannot fail.
        let _ = writeln!(out, "\noutput {} {{", kdl_string(&output.name));
        write_niri_body(&mut out, output);
        out.push_str("}\n");
    }
    out
}

fn write_niri_body(out: &mut String, output: &Output) {
    if !output.enabled {
        out.push_str("    off\n");
        return;
    }
    if let Some(source) = &output.mirror_of {
        let _ = writeln!(out, "    // mirrors {source}: niri cannot mirror outputs");
    }
    if let Some(mode) = output.mode {
        let text = if mode.refresh_mhz == 0 {
            format!("{}x{}", mode.width, mode.height)
        } else {
            format!("{}x{}@{}", mode.width, mode.height, mode.refresh_hz())
        };
        let _ = writeln!(out, "    mode {}", kdl_string(&text));
    }
    let _ = writeln!(out, "    scale {}", output.scale);
    let _ = writeln!(
        out,
        "    transform {}",
        kdl_string(output.transform.as_str())
    );
    let _ = writeln!(
        out,
        "    position x={} y={}",
        output.position.x, output.position.y
    );
    match output.adaptive_sync {
        Some(AdaptiveSync::Always) => out.push_str("    variable-refresh-rate\n"),
        Some(AdaptiveSync::Automatic) => {
            out.push_str("    variable-refresh-rate on-demand=true\n");
        }
        Some(AdaptiveSync::Disabled) | None => {}
    }
    if output.primary {
        out.push_str("    focus-at-startup\n");
    }
}

/// sway `output` commands, one line per output.
///
/// sway mirrors nothing natively either; mirrored outputs become comments.
#[must_use]
pub fn sway(layout: &Layout) -> String {
    let mut out = String::from("# Generated by Vernier (vnr layout export --to sway)\n");
    for output in &layout.outputs {
        let name = kdl_string(&output.name);
        if !output.enabled {
            let _ = writeln!(out, "output {name} disable");
            continue;
        }
        if let Some(source) = &output.mirror_of {
            let _ = writeln!(out, "# {name} mirrors {source}: sway cannot mirror outputs");
        }
        let _ = write!(out, "output {name} enable");
        if let Some(mode) = output.mode {
            let _ = write!(out, " mode {mode}");
        }
        let _ = write!(
            out,
            " position {} {} scale {} transform {}",
            output.position.x, output.position.y, output.scale, output.transform
        );
        match output.adaptive_sync {
            Some(AdaptiveSync::Always | AdaptiveSync::Automatic) => {
                out.push_str(" adaptive_sync on");
            }
            Some(AdaptiveSync::Disabled) => out.push_str(" adaptive_sync off"),
            None => {}
        }
        out.push('\n');
    }
    out
}

/// A kanshi `profile` block matching the layout's outputs by name.
///
/// kanshi applies the profile whenever exactly these outputs are connected.
/// It cannot mirror; mirrored outputs are noted in a comment.
#[must_use]
pub fn kanshi(layout: &Layout) -> String {
    let mut out = String::from("# Generated by Vernier (vnr layout export --to kanshi)\n");
    let _ = writeln!(out, "profile {PROFILE_NAME} {{");
    for output in &layout.outputs {
        let name = kdl_string(&output.name);
        if !output.enabled {
            let _ = writeln!(out, "    output {name} disable");
            continue;
        }
        if let Some(source) = &output.mirror_of {
            let _ = writeln!(
                out,
                "    # {name} mirrors {source}: kanshi cannot mirror outputs"
            );
        }
        let _ = write!(out, "    output {name} enable");
        if let Some(mode) = output.mode {
            let _ = write!(out, " mode {mode}");
        }
        let _ = write!(
            out,
            " position {},{} scale {} transform {}",
            output.position.x, output.position.y, output.scale, output.transform
        );
        if let Some(on) = adaptive_sync(output) {
            out.push_str(if on {
                " adaptive_sync on"
            } else {
                " adaptive_sync off"
            });
        }
        out.push('\n');
    }
    out.push_str("}\n");
    out
}

/// A shikane `[[profile]]` matching the layout's outputs by exact name.
#[must_use]
pub fn shikane(layout: &Layout) -> String {
    let mut out = String::from("# Generated by Vernier (vnr layout export --to shikane)\n");
    let _ = writeln!(out, "\n[[profile]]\nname = {}", kdl_string(PROFILE_NAME));
    for output in &layout.outputs {
        let _ = writeln!(
            out,
            "\n[[profile.output]]\nsearch = {}\nenable = {}",
            kdl_string(&format!("n={}", output.name)),
            output.enabled
        );
        if !output.enabled {
            continue;
        }
        if let Some(source) = &output.mirror_of {
            let _ = writeln!(out, "# mirrors {source}: shikane cannot mirror outputs");
        }
        if let Some(mode) = output.mode {
            let _ = writeln!(out, "mode = {}", kdl_string(&mode.to_string()));
        }
        let _ = writeln!(
            out,
            "position = \"{},{}\"\nscale = {}\ntransform = {}",
            output.position.x,
            output.position.y,
            float_literal(output.scale),
            kdl_string(output.transform.as_str())
        );
        if let Some(on) = adaptive_sync(output) {
            let _ = writeln!(out, "adaptive_sync = {on}");
        }
    }
    out
}

/// home-manager's `services.kanshi` settings for the layout, the same
/// profile as [`kanshi`] in Nix, to merge into a home-manager configuration.
#[must_use]
pub fn home_manager(layout: &Layout) -> String {
    let mut out = String::from(
        "# Generated by Vernier (vnr layout export --to home-manager)\n\
         {\n  services.kanshi = {\n    enable = true;\n    settings = [\n      {\n",
    );
    let _ = writeln!(
        out,
        "        profile.name = {};\n        profile.outputs = [",
        nix_string(PROFILE_NAME)
    );
    for output in &layout.outputs {
        let _ = writeln!(
            out,
            "          {{\n            criteria = {};",
            nix_string(&output.name)
        );
        if output.enabled {
            out.push_str("            status = \"enable\";\n");
            if let Some(source) = &output.mirror_of {
                let _ = writeln!(
                    out,
                    "            # mirrors {source}: kanshi cannot mirror outputs"
                );
            }
            if let Some(mode) = output.mode {
                let _ = writeln!(out, "            mode = {};", nix_string(&mode.to_string()));
            }
            let _ = writeln!(
                out,
                "            position = \"{},{}\";\n            scale = {};\n            transform = {};",
                output.position.x,
                output.position.y,
                float_literal(output.scale),
                nix_string(output.transform.as_str())
            );
            if let Some(on) = adaptive_sync(output) {
                let _ = writeln!(out, "            adaptiveSync = {on};");
            }
        } else {
            out.push_str("            status = \"disable\";\n");
        }
        out.push_str("          }\n");
    }
    out.push_str("        ];\n      }\n    ];\n  };\n}\n");
    out
}

/// Whether adaptive sync should be on, for formats with only on and off.
const fn adaptive_sync(output: &Output) -> Option<bool> {
    match output.adaptive_sync {
        Some(AdaptiveSync::Always | AdaptiveSync::Automatic) => Some(true),
        Some(AdaptiveSync::Disabled) => Some(false),
        None => None,
    }
}

/// A scale as a float literal: TOML and Nix read `1` as an integer, which
/// shikane and home-manager's `types.float` reject.
fn float_literal(scale: Scale) -> String {
    let text = scale.to_string();
    if text.contains('.') {
        text
    } else {
        text + ".0"
    }
}

/// Quotes a string as a Nix string literal.
fn nix_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    let mut chars = value.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '$' if chars.peek() == Some(&'{') => out.push_str("\\$"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{Mode, Position, Transform};

    fn layout() -> Layout {
        let mut a = Output::new("eDP-1");
        a.mode = Some(Mode::new(2880, 1800, 120_000));
        a.scale = Scale::from_millis(1750).unwrap();
        a.adaptive_sync = Some(AdaptiveSync::Automatic);
        let mut b = Output::new("DP-1");
        b.mode = Some(Mode::new(2560, 1440, 59_951));
        b.position = Position::new(1646, 0);
        b.transform = Transform::Rotate90;
        let mut c = Output::new("HDMI-A-1");
        c.enabled = false;
        Layout::new(vec![a, b, c])
    }

    #[test]
    fn niri_snippet() {
        let text = niri(&layout());
        assert!(
            text.contains("output \"eDP-1\" {\n    mode \"2880x1800@120.000\"\n    scale 1.75\n")
        );
        assert!(text.contains("    variable-refresh-rate on-demand=true\n"));
        assert!(text.contains("    transform \"90\"\n    position x=1646 y=0\n"));
        assert!(text.contains("output \"HDMI-A-1\" {\n    off\n}"));
    }

    #[test]
    fn sway_snippet() {
        let text = sway(&layout());
        assert!(text.contains(
            "output \"DP-1\" enable mode 2560x1440@59.951Hz position 1646 0 scale 1 transform 90\n"
        ));
        assert!(text.contains("output \"HDMI-A-1\" disable\n"));
    }

    #[test]
    fn kanshi_snippet() {
        let text = kanshi(&layout());
        assert!(text.starts_with("# Generated by Vernier"));
        assert!(text.contains("profile vernier {\n"));
        assert!(text.contains(
            "    output \"eDP-1\" enable mode 2880x1800@120.000Hz position 0,0 scale 1.75 transform normal adaptive_sync on\n"
        ));
        assert!(text.contains(
            "    output \"DP-1\" enable mode 2560x1440@59.951Hz position 1646,0 scale 1 transform 90\n"
        ));
        assert!(text.contains("    output \"HDMI-A-1\" disable\n}\n"));
    }

    #[test]
    fn shikane_snippet() {
        let text = shikane(&layout());
        assert!(text.contains("[[profile]]\nname = \"vernier\"\n"));
        assert!(text.contains(
            "[[profile.output]]\nsearch = \"n=eDP-1\"\nenable = true\nmode = \"2880x1800@120.000Hz\"\nposition = \"0,0\"\nscale = 1.75\ntransform = \"normal\"\nadaptive_sync = true\n"
        ));
        assert!(text.contains("search = \"n=DP-1\"\nenable = true\nmode = \"2560x1440@59.951Hz\"\nposition = \"1646,0\"\nscale = 1.0\n"));
        assert!(text.contains("search = \"n=HDMI-A-1\"\nenable = false\n"));
        assert!(!text.contains("enable = false\nmode"));
    }

    #[test]
    fn home_manager_snippet() {
        let text = home_manager(&layout());
        assert!(text.contains("services.kanshi = {\n    enable = true;\n"));
        assert!(text.contains("profile.name = \"vernier\";"));
        assert!(text.contains(
            "criteria = \"DP-1\";\n            status = \"enable\";\n            mode = \"2560x1440@59.951Hz\";\n            position = \"1646,0\";\n            scale = 1.0;\n            transform = \"90\";\n"
        ));
        assert!(
            text.contains(
                "criteria = \"HDMI-A-1\";\n            status = \"disable\";\n          }"
            )
        );
        // Braces balance, so the attribute set parses.
        assert_eq!(text.matches('{').count(), text.matches('}').count());
        assert_eq!(text.matches('[').count(), text.matches(']').count());
    }

    #[test]
    fn nix_strings_are_escaped() {
        assert_eq!(nix_string(r#"a"b\c${d}$e"#), r#""a\"b\\c\${d}$e""#);
    }

    #[test]
    fn every_format_round_trips_its_name() {
        for format in Format::ALL {
            assert_eq!(format.as_str().parse::<Format>().ok(), Some(format));
        }
    }

    #[test]
    fn every_export_counts_as_generated() {
        for format in Format::ALL {
            assert!(is_generated(&render(&layout(), format)), "{format}");
        }
        assert!(!is_generated("output \"eDP-1\" { off; }\n"));
        assert!(!is_generated("// my niri config\n"));
    }

    #[test]
    fn kdl_strings_are_escaped() {
        assert_eq!(kdl_string(r#"a"b\c"#), r#""a\"b\\c""#);
    }
}
