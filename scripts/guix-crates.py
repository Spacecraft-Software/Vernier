"""Regenerate the crate list in packaging/guix.scm from Cargo.lock.

Guix builds Rust programs from one `crate-source' origin per crate. The
hash Guix wants is the SHA-256 of the .crate file, which Cargo.lock already
records as hex; this script converts each to Guix's nix-base32 form and
rewrites the block between the BEGIN and END markers. Run it after every
change to Cargo.lock:

    python3 scripts/guix-crates.py

`--check' exits 1 instead of writing when the file is out of date (CI).
"""

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "Cargo.lock"
GUIX = ROOT / "packaging" / "guix.scm"
BEGIN = ";;; BEGIN generated by scripts/guix-crates.py; do not edit by hand.\n"
END = ";;; END generated crates.\n"
REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"
ALPHABET = "0123456789abcdfghijklmnpqrsvwxyz"  # Nix base32, no e o t u


def nix_base32(digest: bytes) -> str:
    """Nix's base32 encoding, as Guix's `base32' reader expects it."""
    length = (len(digest) * 8 - 1) // 5 + 1
    out = []
    for n in range(length - 1, -1, -1):
        bit = n * 5
        i, j = divmod(bit, 8)
        c = digest[i] >> j
        if i + 1 < len(digest):
            c |= digest[i + 1] << (8 - j)
        out.append(ALPHABET[c & 0x1F])
    return "".join(out)


def guix_name(name: str, version: str) -> str:
    return f"rust-{name.replace('_', '-').lower()}-{version}"


def generated() -> str:
    lock = tomllib.loads(LOCK.read_text(encoding="utf-8"))
    crates = sorted(
        (p for p in lock["package"] if p.get("source") == REGISTRY),
        key=lambda p: (p["name"], p["version"]),
    )
    lines = [BEGIN]
    for p in crates:
        digest = bytes.fromhex(p["checksum"])
        lines.append(
            f'(define {guix_name(p["name"], p["version"])}\n'
            f'  (crate-source "{p["name"]}" "{p["version"]}"\n'
            f'                "{nix_base32(digest)}"))\n'
        )
    lines.append("\n(define vernier-cargo-inputs\n  (list")
    lines.extend(f"\n   {guix_name(p['name'], p['version'])}" for p in crates)
    lines.append("))\n")
    lines.append(END)
    return "".join(lines)


def main() -> int:
    text = GUIX.read_text(encoding="utf-8")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + generated() + tail
    if "--check" in sys.argv[1:]:
        if new != text:
            print("packaging/guix.scm is out of date: run scripts/guix-crates.py", file=sys.stderr)
            return 1
        return 0
    GUIX.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
